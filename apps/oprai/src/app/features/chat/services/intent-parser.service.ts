  private parseParams(paramsStr: string): Record<string, string> {
    const params: Record<string, string> = {};
    if (!paramsStr) return params;

    // Regex to capture:
    // - angle brackets: key=<value>
    // - double quotes: key="value" (including key="" for empty strings)
    // - simple: key=value (no spaces)
    const paramRegex = /(\w+)=(?:<([^>]+)>|"([^"]*)"|(\S+))/g;
    let paramMatch: RegExpExecArray | null;

    while ((paramMatch = paramRegex.exec(paramsStr)) !== null) {
      const key = paramMatch[1];
      const value = paramMatch[2] ?? paramMatch[3] ?? paramMatch[4] ?? '';
      try {
        params[key] = decodeURIComponent(value);
      } catch {
        params[key] = value;
      }
    }

    return params;
  }

  /** Parse JSON-formatted params block: {"key": "value", ...} */
  private parseJsonParams(jsonStr: string): Record<string, string> {
    try {
      const obj = JSON.parse(jsonStr);
      return this.normalizeToStringRecord(obj);
    } catch {
      // Invalid JSON -> fall back to legacy parser
      return this.parseParams(jsonStr);
    }
  }

  /** Convert all values to strings (LLM may send number/boolean) */
  private normalizeToStringRecord(obj: Record<string, unknown>): Record<string, string> {
    const result: Record<string, string> = {};
    for (const [k, v] of Object.entries(obj)) {
      if (v === null || v === undefined) continue;
      if (typeof v === 'object') {
        result[k] = JSON.stringify(v);
      } else {
        result[k] = String(v);
      }
    }
    return result;
  }

  /**
   * Validate parsed action params — returns an array of human-readable error strings.
   * Empty array = valid. Callers can warn users or drop invalid actions.
   */
  validateActionParams(type: string, params: Record<string, string>): string[] {
    const errors: string[] = [];

    const requireParam = (key: string, label?: string) => {
      if (!params[key]?.trim()) errors.push(`Missing required param: ${label ?? key}`);
    };

    const requireNumeric = (key: string) => {
      const v = params[key];
      if (v !== undefined && isNaN(parseFloat(v))) {
        errors.push(`Param "${key}" must be a number (got: ${v})`);
      }
    };

    const requirePositive = (key: string) => {
      const v = parseFloat(params[key] ?? '');
      if (!isNaN(v) && v <= 0) {
        errors.push(`Param "${key}" must be greater than 0`);
      }
    };

    const requireAddress = (key: string) => {
      const v = params[key];
      if (v && !/^[1-9A-HJ-NP-Za-km-z]{32,44}$/.test(v)) {
        errors.push(`Param "${key}" must be a valid Solana address (got: ${v})`);
      }
    };

    const requireSlippage = (key = 'slippageBps') => {
      const v = parseFloat(params[key] ?? '');
      if (!isNaN(v) && (v < 0 || v > 10_000)) {
        errors.push(`Slippage must be between 0 and 10000 bps`);
      }
    };

    switch (type) {
      case 'swap':
      case 'limit_order':
        requireParam('inputMint'); requireAddress('inputMint');
        requireParam('outputMint'); requireAddress('outputMint');
        requireParam('amount'); requireNumeric('amount'); requirePositive('amount');
        requireSlippage();
        break;
      case 'dca':
        requireParam('inputMint'); requireParam('outputMint');
        requireParam('totalAmount'); requireNumeric('totalAmount'); requirePositive('totalAmount');
        break;
      case 'transfer':
        requireParam('to', 'recipient address'); requireAddress('to');
        requireParam('amount'); requireNumeric('amount'); requirePositive('amount');
        break;
      case 'stake':
      case 'unstake':
      case 'marinade_stake':
      case 'marinade_unstake':
      case 'marinade_delayed_unstake':
      case 'jupsol_stake':
      case 'jupsol_unstake':
        requireParam('amount'); requireNumeric('amount'); requirePositive('amount');
        break;
      case 'marinade_claim_ticket':
      case 'marinade_claim':
        requireParam('ticketAccount', 'ticket account'); requireAddress('ticketAccount');
        break;
      case 'pumpfun_buy':
      case 'pumpfun_sell':
      case 'pumpswap_buy':
      case 'pumpswap_sell':
        requireParam('mint'); requireAddress('mint');
        requireParam('amount'); requireNumeric('amount'); requirePositive('amount');
        break;
      case 'pumpfun_launch':
        requireParam('name'); requireParam('symbol'); requireParam('description');
        if (!params['imageUrl'] && !params['metadataUri']) {
          errors.push('Either imageUrl or metadataUri is required for token launch');
        }
        break;
      case 'marginfi_deposit':
      case 'marginfi_withdraw':
      case 'marginfi_borrow':
      case 'marginfi_repay':
        requireParam('bank', 'bank/token'); requireParam('amount');
        requireNumeric('amount'); requirePositive('amount');
        break;
      case 'kamino_deposit':
      case 'kamino_borrow':
        requireParam('token'); requireParam('amount');
        requireNumeric('amount'); requirePositive('amount');
        break;
    }

    return errors;
  }

  /**
   * JSON extraction with nested {} support.
   * `startIdx` = index of the opening { character in content.
   * Returns the full JSON string, or null if it cannot be parsed.
   */
  private extractBalancedJson(content: string, startIdx: number): string | null {
    let depth = 0;
    let i = startIdx;
    let inString = false;
    let escape = false;

    while (i < content.length) {
      const ch = content[i];

      if (escape) { escape = false; i++; continue; }
      if (ch === '\\' && inString) { escape = true; i++; continue; }
      if (ch === '"') { inString = !inString; i++; continue; }
      if (inString) { i++; continue; }

      if (ch === '{') depth++;
      else if (ch === '}') {
        depth--;
        if (depth === 0) return content.slice(startIdx, i + 1);
      }
      i++;
    }
    return null;
  }
