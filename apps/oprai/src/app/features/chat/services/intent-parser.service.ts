import { Injectable } from '@angular/core';

export interface ParsedAction {
  type: string;
  params: Record<string, string>;
  raw: string;
  /** Chain this action to the previous one's output.
   * E.g., swap output → stake input (jitoSOL)
   * When true, the output of previous action is used as input for this action. */
  chainFromPrevious?: boolean;
}

export interface ParsedQuery {
  type: string;
  params: Record<string, string>;
  raw: string;
}

/** Single option — runs as ACTION immediately when clicked */
export interface ClarifyOption {
  label: string;
  sublabel?: string;
  action: string;
  params: Record<string, string>;
}

/** [CLARIFY:type] block generated by LLM for protocol ambiguity */
export interface ParsedClarify {
  category: string;
  question: string;
  options: ClarifyOption[];
  raw: string;
}

export interface ParsedIntent {
  actions: ParsedAction[];
  queries: ParsedQuery[];
  clarifications: ParsedClarify[];
}

